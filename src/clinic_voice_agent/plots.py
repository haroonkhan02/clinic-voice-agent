"""Latency analysis and figures from the saved reports (no API calls).

Reads reports/speech_roundtrip.json, phone_sim.json, flux_eot_sweep.json and
local_speech.json (whichever exist) and writes:

- reports/latency_analysis.md: Flux end-of-turn delay by guardrail label, and how much of the
  simulated calls' voice-to-voice time it explains (Pearson r, median remainder).
- reports/figures/*.png: the plots used in the README.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

LABEL_ORDER = ("emergency", "medical_advice", "ok")
COLORS = {"emergency": "#c0392b", "medical_advice": "#2471a3", "ok": "#7f8c8d"}


def _load(path: Path) -> Any | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pearson(x: list[float], y: list[float]) -> float:
    mx, my = statistics.fmean(x), statistics.fmean(y)
    sxy = sum((a - mx) * (b - my) for a, b in zip(x, y, strict=True))
    sxx = sum((a - mx) ** 2 for a in x)
    syy = sum((b - my) ** 2 for b in y)
    return sxy / (sxx * syy) ** 0.5


def eot_by_label(speech: dict) -> dict[str, list[float]]:
    out: dict[str, list[float]] = {label: [] for label in LABEL_ORDER}
    for item in speech["items"]:
        if item["label"] in out and item["flux_eot_latency_s"] is not None:
            out[item["label"]].append(item["flux_eot_latency_s"])
    return out


def analyse(reports: Path) -> dict[str, Any]:
    speech = _load(reports / "speech_roundtrip.json")
    sim = _load(reports / "phone_sim.json")
    result: dict[str, Any] = {}
    if speech:
        result["eot_by_label"] = {
            label: {"median": statistics.median(v), "n": len(v)}
            for label, v in eot_by_label(speech).items() if v
        }
    if speech and sim:
        eot = {i["text"]: i["flux_eot_latency_s"] for i in speech["items"]}
        pairs = [(eot[c["text"]], c["voice_to_voice_s"]) for c in sim["calls"]
                 if eot.get(c["text"]) is not None and c["voice_to_voice_s"] is not None]
        x, y = [p[0] for p in pairs], [p[1] for p in pairs]
        result["sim_vs_eot"] = {
            "n": len(pairs),
            "pearson_r": pearson(x, y),
            "median_remainder_s": statistics.median(b - a for a, b in pairs),
            "pairs": pairs,
        }
    return result


def write_analysis(result: dict[str, Any], reports: Path) -> None:
    lines = ["# Where the voice-to-voice time goes", "",
             "Generated by `cva-plots` from `speech_roundtrip.json` and `phone_sim.json`.", ""]
    if "eot_by_label" in result:
        lines += ["Flux end-of-turn delay (end of speech → `EndOfTurn`) on the labelled caller "
                  "lines, by guardrail label:", "",
                  "| Label | Median delay (s) | n |", "|---|---|---|"]
        lines += [f"| {label} | {m['median']:.2f} | {m['n']} |"
                  for label, m in result["eot_by_label"].items()]
    if "sim_vs_eot" in result:
        s = result["sim_vs_eot"]
        lines += ["", f"Simulated calls: the same line's Flux delay in the speech eval and its "
                  f"voice-to-voice time in the phone simulation correlate with Pearson r = "
                  f"{s['pearson_r']:.2f} (n = {s['n']}). The median remainder (voice-to-voice "
                  f"minus end-of-turn delay: gate, TTS first audio, transport) is "
                  f"{s['median_remainder_s']:.2f} s. The two numbers come from separate "
                  "Flux streams on different days, so the remainder is only a rough estimate; "
                  "the correlation is the robust part."]
    (reports / "latency_analysis.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def make_figures(result: dict[str, Any], reports: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig_dir = reports / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    written = []
    speech = _load(reports / "speech_roundtrip.json")
    sweep = _load(reports / "flux_eot_sweep.json")

    panels = [p for p in (speech, "sim_vs_eot" in result, sweep) if p]
    fig, axes = plt.subplots(1, len(panels), figsize=(5.2 * len(panels), 4.0))
    axes = list(axes) if len(panels) > 1 else [axes]
    ax_iter = iter(axes)
    if speech:
        ax = next(ax_iter)
        groups = eot_by_label(speech)
        labels = [lab for lab in LABEL_ORDER if groups[lab]]
        box = ax.boxplot([groups[lab] for lab in labels], patch_artist=True, widths=0.5)
        ax.set_xticks(range(1, len(labels) + 1),
                      [f"{lab.replace('_', ' ')}\n(n={len(groups[lab])})" for lab in labels])
        for patch, lab in zip(box["boxes"], labels, strict=True):
            patch.set_facecolor(COLORS[lab])
            patch.set_alpha(0.55)
        ax.set_ylabel("Flux end-of-turn delay (s)")
        ax.set_title("Statements wait longer than questions")
    if "sim_vs_eot" in result:
        ax = next(ax_iter)
        sim = _load(reports / "phone_sim.json")
        eot = {i["text"]: i["flux_eot_latency_s"] for i in speech["items"]}
        for lab in ("emergency", "medical_advice"):
            pts = [(eot[c["text"]], c["voice_to_voice_s"]) for c in sim["calls"]
                   if c["label"] == lab and c["voice_to_voice_s"] is not None]
            ax.scatter(*zip(*pts, strict=True), color=COLORS[lab], label=lab.replace("_", " "))
        lim = max(max(p) for p in result["sim_vs_eot"]["pairs"]) * 1.1
        ax.plot([0, lim], [0, lim], color="grey", lw=0.8, ls="--", label="y = x")
        ax.set_xlabel("Flux end-of-turn delay, speech eval (s)")
        ax.set_ylabel("Voice-to-voice, simulated call (s)")
        ax.set_title(f"Turn detection drives latency (r = {result['sim_vs_eot']['pearson_r']:.2f})")
        ax.legend(frameon=False)
    if sweep:
        ax = next(ax_iter)
        thr = list(sweep)
        early = [sweep[t]["summary"]["premature_lines"] for t in thr]
        delay = [sweep[t]["summary"]["eot_latency_s"]["median"] for t in thr]
        ax.plot(delay, early, marker="o", color="#2471a3")
        for t, d, e in zip(thr, delay, early, strict=True):
            ax.annotate(f"eot_threshold {t}", (d, e), textcoords="offset points", xytext=(6, 4),
                        fontsize=8)
        ax.set_xlabel("Median end-of-turn delay (s)")
        ax.set_ylabel(f"Lines cut off early (of {sweep[thr[0]]['summary']['n']})")
        ax.set_title("Answering sooner means interrupting more")
    for ax in axes:
        ax.grid(alpha=0.3)
    fig.tight_layout()
    path = fig_dir / "latency.png"
    fig.savefig(path, dpi=130)
    plt.close(fig)
    written.append(path)
    return written
