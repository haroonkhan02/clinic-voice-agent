"""Flux end-of-turn settings: how early does the bot cut in, and how long does it wait?

Flux decides that the caller has finished when its end-of-turn confidence passes
`eot_threshold` (default 0.7), or after `eot_timeout_ms` of silence. A low threshold answers
sooner but sometimes interrupts a caller who only paused (reading out a phone number, "no
thank you, ... that's all"). A high threshold waits longer on every turn.

This replays the cached phone audio from `cva-speech-eval` (no new TTS) through Flux with
each setting, at real-time pace, and records per line: premature EndOfTurn events, the delay
from end of speech to the final EndOfTurn, the word error rate and the guardrail decision.
"""

from __future__ import annotations

import asyncio
import json
import os
from pathlib import Path
from typing import Any

from clinic_voice_agent.audio import mulaw_to_pcm16, word_errors
from clinic_voice_agent.guardrails import screen
from clinic_voice_agent.speech_eval import Item, _stats, transcribe_flux

DEFAULT_THRESHOLDS = (0.7, 0.8, 0.9)


def cached_audio(item: Item, cache_dir: Path) -> bytes:
    import hashlib

    from clinic_voice_agent.speech_eval import TTS_VOICE

    name = hashlib.sha1(f"{TTS_VOICE}|{item.text}".encode()).hexdigest()[:16]
    path = cache_dir / f"{name}.ulaw"
    if not path.exists():
        raise FileNotFoundError(f"no cached audio for {item.text!r}: run cva-speech-eval first")
    return path.read_bytes()


async def run_setting(items: list[Item], cache_dir: Path, key: str, threshold: float,
                      progress=print) -> list[dict[str, Any]]:
    rows = []
    for n, item in enumerate(items, 1):
        pcm = mulaw_to_pcm16(cached_audio(item, cache_dir))
        for attempt in range(3):
            try:
                text, eot, premature = await transcribe_flux(
                    pcm, key, params={"eot_threshold": threshold})
                break
            except OSError:
                if attempt == 2:
                    raise
                await asyncio.sleep(1 + attempt)
        edits, ref = word_errors(item.text, text)
        rows.append({"text": item.text, "label": item.label, "transcript": text,
                     "eot_latency_s": eot, "premature_eots": premature, "edits": edits,
                     "ref_words": ref, "guard_text": screen(item.text).action,
                     "guard_transcript": screen(text).action})
        progress(f"[thr {threshold}] {n}/{len(items)} eot={eot} premature={premature}")
    return rows


def summarise_setting(rows: list[dict[str, Any]]) -> dict[str, Any]:
    lat = [r["eot_latency_s"] for r in rows if r["eot_latency_s"] is not None]
    return {
        "n": len(rows),
        "premature_lines": sum(r["premature_eots"] > 0 for r in rows),
        "premature_events": sum(r["premature_eots"] for r in rows),
        "no_final_eot": sum(r["eot_latency_s"] is None for r in rows),
        "eot_latency_s": _stats(lat),
        "wer": sum(r["edits"] for r in rows) / max(1, sum(r["ref_words"] for r in rows)),
        "guardrail_agreement": sum(r["guard_text"] == r["guard_transcript"] for r in rows)
        / max(1, len(rows)),
        "premature_texts": [r["text"] for r in rows if r["premature_eots"]],
    }


async def sweep(items: list[Item], cache_dir: Path, thresholds=DEFAULT_THRESHOLDS,
                progress=print) -> dict[str, Any]:
    key = os.environ["DEEPGRAM_API_KEY"]
    # Settings run concurrently (one stream each); lines within a setting run one by one.
    results = await asyncio.gather(
        *(run_setting(items, cache_dir, key, t, progress) for t in thresholds))
    return {str(t): {"summary": summarise_setting(rows), "items": rows}
            for t, rows in zip(thresholds, results, strict=True)}


def write_report(result: dict[str, Any], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "flux_eot_sweep.json").write_text(
        json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    first = next(iter(result.values()))["summary"]
    lines = [
        "# Flux end-of-turn threshold sweep",
        "",
        f"{first['n']} caller lines (cached 8 kHz μ-law audio from `cva-speech-eval`), streamed "
        "at real-time pace once per setting. Generated by `cva-flux-sweep`.",
        "",
        "| eot_threshold | Lines cut off early | Early EndOfTurn events | Median end-of-turn delay "
        "(s) | p90 (s) | WER | Guardrail decision unchanged |",
        "|---|---|---|---|---|---|---|",
    ]
    for t, block in result.items():
        s = block["summary"]
        lat = s["eot_latency_s"]
        med = "n/a" if lat["median"] is None else f"{lat['median']:.2f}"
        p90 = "n/a" if lat["p90"] is None else f"{lat['p90']:.2f}"
        lines.append(f"| {t} | {s['premature_lines']} / {s['n']} | {s['premature_events']} | "
                     f"{med} | {p90} | {s['wer']:.3f} | {s['guardrail_agreement']:.3f} |")
    for t, block in result.items():
        texts = block["summary"]["premature_texts"]
        lines += ["", f"**Cut off early at {t}** ({len(texts)})", ""]
        lines += [f"- *{x}*" for x in texts] or ["None."]
    (out_dir / "flux_eot_sweep.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
